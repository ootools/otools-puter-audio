/**
 * 模式表：带插值的文案按形状认。
 * ------------------------------------------------------------------
 * 上游有大量文案是模板串拼出来的（`Opening ${name}...`、`${n} files added`），
 * 永远不可能成为词典的键，只能按形状认。
 *
 * 每条都是**锚定正则**（`^…$`，不带 `g`）。替换函数返回**空串**表示
 * 「这条不适用」，让文案保持英文并出现在缺口报告里——宁可半句英文，
 * 也别拼出「重置 Reset all」这种半成品。
 *
 * 捕获组若是界面文案（方向词、状态词）就递归再翻一次；若是用户数据
 * （文件名、轨道名）就原样保留。
 *
 * 只收「反复出现、看得见」的那几类：状态栏进度、toast 计数、面板 aria-label、
 * 时长/容量格式。长尾的拼串留白（保持英文），别在这里硬凑。
 */
export const patterns = [
  /* ------------------------------------------------------ 状态栏 / 进度 */
  [/^Opening (.+)\.\.\.$/, (m) => `正在打开 ${m[1]}...`],
  [/^Opened in ([\d.]+) seconds$/, (m) => `已在 ${m[1]} 秒内打开`],
  [/^Launched in ([\d.]+) seconds$/, (m) => `已在 ${m[1]} 秒内启动`],
  [/^Scanning (.+)\.\.\.$/, (m) => `正在扫描 ${m[1]}...`],
  [/^Running (.+)\.\.\.$/, (m) => `正在运行 ${m[1]}...`],
  [/^Saving (.+)$/, (m) => `正在保存 ${m[1]}`],
  [/^Could not open (.+)$/, (m) => `无法打开 ${m[1]}`],
  [/^Batch output saved to (.+)$/, (m) => `批处理输出已保存到 ${m[1]}`],
  [/^Split into (\d+) band files$/, (m) => `已拆分为 ${m[1]} 个频段文件`],
  [/^Extracted (\d+) mono files$/, (m) => `已提取 ${m[1]} 个单声道文件`],
  [/^Saved preset (.+)$/, (m) => `已保存预设 ${m[1]}`],
  [/^Preset (.+)$/, (m) => `预设 ${m[1]}`],
  [/^Audio type set to (.+)$/, (m, t) => `音频类型已设为 ${t(m[1])}`],
  [/^(\d+) bands$/, (m) => `${m[1]} 个频段`],
  [/^Clip stretched to ([\d.]+)%$/, (m) => `片段已拉伸至 ${m[1]}%`],
  [/^Shuttle (backward|forward) ([\d.]+)x$/, (m) => `穿梭${m[1] === 'backward' ? '向后' : '向前'} ${m[2]}x`],
  [/^Hold (\d+) cleared$/, (m) => `已清除保持 ${m[1]}`],
  [/^Trace held in slot (\d+)$/, (m) => `轨迹已保存在槽位 ${m[1]}`],
  [/^Now interpreted at (\d+) Hz \((faster|slower) playback\)$/, (m) => `现在按 ${m[1]} Hz 解释（${m[2] === 'faster' ? '更快' : '更慢'}播放）`],

  /* ---------------------------------------------------------- 计数提示 */
  [/^(\d+) files? added$/, (m) => `已添加 ${m[1]} 个文件`],
  [/^(\d+) files? removed$/, (m) => `已移除 ${m[1]} 个文件`],
  [/^Added (\d+) markers? to the playlist$/, (m) => `已向播放列表添加 ${m[1]} 个标记`],
  [/^Recovered (\d+) files?\. Save to keep (?:them|it)\.$/, (m) => `已恢复 ${m[1]} 个文件。保存以保留。`],
  [/^Restored (\d+) sessions?\. Save to keep (?:them|it)\.$/, (m) => `已恢复 ${m[1]} 个会话。保存以保留。`],

  /* -------------------------------------------------------- 面板 / 控件 */
  // 工作区名字是**用户数据**（默认叫 Default，但用户可以改名），整段保留不翻。
  [/^(.+) workspace menu$/, (m) => `${m[1]} 工作区菜单`],
  [/^(.+) workspace$/, (m) => `${m[1]} 工作区`],
  [/^(.+) panel group$/, (m, t) => `${t(m[1])}面板组`],
  [/^(.+) panel menu$/, (m, t) => `${t(m[1])}面板菜单`],
  [/^(.+) level$/, (m) => `${m[1]} 电平`],
  [/^Multitrack session (.+)$/, (m) => `多轨会话 ${m[1]}`],
  [/^Waveform of (.+)$/, (m) => `${m[1]} 的波形`],
  [/^Track (.+)$/, (m) => `轨道 ${m[1]}`],
  [/^Clear (.+)$/, (m, t) => `清除 ${t(m[1])}`],
  [/^Clipboard (\d+) is now active \(empty\)$/, (m) => `剪贴板 ${m[1]} 已激活（空）`],
  [/^Clipboard (\d+) is now active$/, (m) => `剪贴板 ${m[1]} 已激活`],
  [/^Clipboard (\d+)$/, (m) => `剪贴板 ${m[1]}`],
  [/^(\d+) Undo$/, (m) => `${m[1]} 步撤销`],
  [/^(\d+) Redo$/, (m) => `${m[1]} 步重做`],
  [/^Zoom to Preset (\d+)$/, (m) => `缩放至预设 ${m[1]}`],
  [/^Save Current Zoom to Preset (\d+)$/, (m) => `将当前缩放保存为预设 ${m[1]}`],
  [/^Toggle (.+) Channel$/, (m, t) => `切换 ${t(m[1])} 声道`],
  [/^(.+) channel (disabled|enabled)$/, (m, t) => `${t(m[1])} 声道${m[2] === 'disabled' ? '已停用' : '已启用'}`],
  [/^Center Playhead While Scrolling \((.+)\)$/, (m, t) => `滚动时居中播放头（${t(m[1])}）`],
  [/^FFT size (.+)$/, (m) => `FFT 大小 ${m[1]}`],
  [/^(.+) amount$/, (m, t) => `${t(m[1])} 数量`],

  /* ------------------------------------------------------ 用户数据内嵌 */
  [/^"(.+)" is a folder\. Open audio files from it in the Media Browser\.$/, (m) => `“${m[1]}”是文件夹。请在媒体浏览器中打开其中的音频文件。`],
  [/^"(.+)" could not be opened\. It may have been moved or deleted\.$/, (m) => `无法打开“${m[1]}”。它可能已被移动或删除。`],
  [/^"(.+)" could not be recovered\.$/, (m) => `无法恢复“${m[1]}”。`],
  [/^"(.+)" could not be restored\.$/, (m) => `无法还原“${m[1]}”。`],
  [/^The session "(.+)" is no longer open\.$/, (m) => `会话“${m[1]}”已关闭。`],
  [/^Preset "(.+)" saved\.$/, (m) => `预设“${m[1]}”已保存。`],
  [/^Delete the preset "(.+)"\?$/, (m) => `删除预设“${m[1]}”？`],
  [/^Discard all changes to "(.+)" since it was last saved\?$/, (m) => `放弃对“${m[1]}”自上次保存以来的所有更改？`],
  [/^Signed in as (.+)$/, (m) => `当前身份：${m[1]}`],

  /* ------------------------------------------------------ 时长 / 容量 */
  [/^(\d+) h (\d+) min$/, (m) => `${m[1]} 小时 ${m[2]} 分`],
  [/^(\d+) min$/, (m) => `${m[1]} 分`],
  [/^(\d+) s$/, (m) => `${m[1]} 秒`],
  [/^([\d.]+ [A-Za-z]+) free$/, (m) => `可用 ${m[1]}`],
  [/^(\d+) samples$/, (m) => `${m[1]} 个采样`],
];
